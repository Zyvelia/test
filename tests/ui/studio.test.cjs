'use strict';
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {spawnSync}=require('node:child_process');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'../..');
const fixture=spawnSync(process.env.VIVI_PYTHON||'python',[path.join(__dirname,'render_fixture.py')],{cwd:root,encoding:'utf8'});
assert.equal(fixture.status,0,fixture.stderr);
const dom=new JSDOM(fixture.stdout,{runScripts:'outside-only',url:'http://127.0.0.1:8765/'});
const {window}=dom;const doc=window.document;
window.HTMLCanvasElement.prototype.getContext=()=>({fillRect(){},beginPath(){},arc(){},fill(){},fillText(){}});
window.eval(readFileSync(path.join(root,'vivi/static/studio.js'),'utf8'));
const panels=doc.getElementById('dashboard-panels');
let sections=[...panels.querySelectorAll(':scope > details')];
const first=sections[0];first.querySelectorAll('summary button')[1].click();
assert.equal(panels.querySelectorAll(':scope > details')[1],first,'keyboard panel move must change panel order');
const panelForm=doc.getElementById('panel-layout-form');panelForm.dispatchEvent(new window.Event('submit',{cancelable:true}));
assert.equal(JSON.parse(panelForm.elements.layout.value)[1],first.dataset.panel);
const welcome=doc.querySelector('[data-editor="welcome"]');
const initial=JSON.parse(welcome.elements.document.value).elements.length;
welcome.querySelector('.new-type').value='text';welcome.querySelector('.add-element').click();
assert.equal(JSON.parse(welcome.elements.document.value).elements.length,initial+1);
const lastField=[...welcome.querySelectorAll('fieldset')].at(-1);const input=lastField.querySelector('textarea');
input.value='<script>literal text</script>';input.dispatchEvent(new window.Event('input'));
assert.equal(JSON.parse(welcome.elements.document.value).elements.at(-1).value,input.value);
lastField.querySelectorAll('button')[0].click();
assert.equal(JSON.parse(welcome.elements.document.value).elements.at(-2).type,'text');
const announcement=doc.querySelector('[data-editor="announcement"]');
const value=announcement.querySelector('textarea');value.value='<img src=x onerror=alert(1)>';value.dispatchEvent(new window.Event('input'));
assert.equal(announcement.querySelector('.announcement-preview img'),null);
assert.ok(announcement.querySelector('.announcement-preview').textContent.includes('<img'));
// Exercise the actual HTML5 drop handler with its source index.
announcement.querySelector('.new-type').value='field';announcement.querySelector('.add-element').click();
const fieldsets=[...announcement.querySelectorAll('fieldset')];const drop=new window.Event('drop',{bubbles:true,cancelable:true});
Object.defineProperty(drop,'dataTransfer',{value:{getData:()=>String(fieldsets.length-1)}});fieldsets[1].dispatchEvent(drop);
assert.equal(JSON.parse(announcement.elements.document.value)[1].type,'field');
const script=readFileSync(path.join(root,'vivi/static/studio.js'),'utf8');assert.ok(!script.includes('innerHTML'));
console.log('Dashboard DOM tests passed: panel keyboard order, form serialization, welcome editing, block drag/drop, escaped preview.');
dom.window.close();
